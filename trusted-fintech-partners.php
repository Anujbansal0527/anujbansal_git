          <p>In 2023, India is going to overtake China as the most populous country in the world with more than 75% literacy rate. Around 95 crore Indians are connected to internet and more than 93 crores of them are smart phone users. All these statistics raise hope towards a better India, which is targeting to become $5 trillion economy by 2025, and the third world’s largest economy by 2027. The Indian Mutual Fund industry is following a parallel growth trend and has set similar targets to cross Rs 100 trillion in AUM before 2030. 
          <p>The Mutual Fund Distributors (MFDs) are the primary pillars of the mutual fund industry and they are the key to unlock this ₹100 trillion potential for the industry, for themselves and the Indian investors. We have identified multiple categories of market expansion that will be required to deliver this growth. 

          <h4>Expand Distribution Network</h4>
          <p>As per the BCG report around 90% of households in India live in smaller cities (tier 2 & beyond). Therefore, it becomes critical to expand the reach beyond metro (tier 1) cities to add and acquire new 8 crore investors. MFDs need to rethink their approach and build a sustainable and more robust distribution network to outreach investors away from their locality. Improving the online or digital presence can be the key to reach such customers.


          <h4>Simplification brings Inclusion</h4>
          <p>Nearly every 3rd Indian belongs to middle class with an annual household income of Rs 5-15 lakh and MFDs need to primarily focus on this less touched community. MFDs continue to lag in delivering superior customer experience, thus it will require a fundamental shift in their business approach. Simplify things from automated on-boarding to multi asset investing will be the key to target these investors. MFDs must offer their clients mutual fund platforms with simpler UIs, simplified KYC process and automated back-end.

          <h4>Gain control over investors’ savings</h4>
          <p>Only MFDs have the capacity to increase the share of mutual funds in the overall savings of Indians, which is currently more concentrated towards traditional investment products. MFDs must have appropriate mutual fund products and the required tech-support to offer investors better returns, lesser risk and higher liquidity. 

          <h4>Goal based planning</h4> 
          <p>India has one of the youngest populations in the world, which is digital-savvy, it is witnessing rising participation of women and it has a large population of elderly also. These are all examples of different customer segments and MFDs can capture these investor groups by properly planning their future financial goals. With proper goals, redemptions get reduced and investors remain invested for longer terms. 


          <h4>Exploit technology </h4>
          <p>Technology can enable MFDs to target lower costing, efficient risk management and improved efficiency; and deliver consistent customer experience without any compromise.

