<script>
    $(document).ready(function () {

        // Function to add aria-labels dynamically
        function addDotLabels($carousel, prefix) {
            $carousel.find('.owl-dot').each(function (index) {
                $(this).attr('aria-label', 'Go to ' + prefix + ' slide ' + (index + 1));
            });
        }

        // Function to mark current slide
        function updateCurrentDot($carousel, event) {
            $carousel.find('.owl-dot').removeAttr('aria-current');
            if (event && event.page && typeof event.page.index === 'number') {
                $carousel.find('.owl-dot').eq(event.page.index).attr('aria-current', 'true');
            } else {
                $carousel.find('.owl-dot.active').attr('aria-current', 'true');
            }
        }

        // Loop through every Owl Carousel
        $('.owl-carousel').each(function (i) {
            var $this = $(this);

            // Decide prefix based on ID or index
            var prefix = $this.attr('id') ?
                $this.attr('id').replace('Carousel', '').replace(/[-_]/g,
                    ' ') // e.g. "featuresCarousel" → "features"
                :
                'carousel ' + (i + 1);

            // Capitalize prefix for better accessibility speech
            prefix = prefix.charAt(0).toUpperCase() + prefix.slice(1);

            // Add labels when initialized
            $this.on('initialized.owl.carousel', function () {
                addDotLabels($this, prefix);
                updateCurrentDot($this);
            });

            // Update aria-current on change
            $this.on('changed.owl.carousel', function (event) {
                updateCurrentDot($this, event);
            });

            // If already initialized
            if ($this.hasClass('owl-loaded')) {
                addDotLabels($this, prefix);
                updateCurrentDot($this);
            }
        });

    });
</script>



