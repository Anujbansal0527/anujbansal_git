        <script>
            document.getElementById('submit_form').addEventListener('click', function (event) {
                event.preventDefault();

                // Button ko disable karne ke liye
                const disabledButton = document.querySelector('.disabled-btn');
                const originalText = disabledButton.innerText;
                disabledButton.disabled = true;
                disabledButton.innerText = "Submitting...";



                let valid = true;

                // Clear old errors
                document.querySelectorAll('.error').forEach(el => el.innerText = '');

                // Validation rules
                const fields = {
                    contact_name: /^[a-zA-Z\s]+$/, // Letters and spaces
                    contact_email: /^[^\s@]+@[^\s@]+\.[^\s@]+$/, // Email format
                    contact_mobile: /^\d{10}$/, // 10-digit mobile
                    contact_city: /^[a-zA-Z\s]+$/, // City letters only
                    contact_arn_No: /^\d+$/, // Digits only
                    message: /^.+$/, // Not empty
                    service: /^.+$/, // Dropdown value not empty
                    con_cap: /^.+$/, // Captcha not empty
                };

                const customMessages = {
                    contact_name: "Please enter valid name",
                    contact_email: "Please enter valid email",
                    contact_mobile: "Please enter valid mobile",
                    contact_city: "Please enter valid city",
                    contact_arn_No: "Please enter valid ARN number",
                    service: "Please select service",
                    message: "Please enter valid message",
                    con_cap: "Please enter valid captcha",
                };

                // Validate all fields
                for (const [field, regex] of Object.entries(fields)) {
                    const input = document.getElementById(field);
                    const value = input ? input.value.trim() : '';
                    if (!value || !regex.test(value)) {
                        document.getElementById(`${field}_msg`).innerText = customMessages[field];
                        valid = false;
                    } else {
                        document.getElementById(`${field}_msg`).innerText = "";
                    }
                }

                // Agar validation fail hua
                if (!valid) {
                    disabledButton.disabled = false; // Button dobara enable
                    disabledButton.innerText = originalText;
                    return;
                }

                // Agar validation pass ho gaya — AJAX call
                const form = document.getElementById('contact_us_form');
                const formData = new FormData(form);

                fetch('contact_data.php', {
                    method: 'POST',
                    body: formData,
                })
                    .then(response => response.json())
                    .then(data => {
                        if (data.status === 'success') {
                            // ✅ Form clear after success
                            form.reset();

                            // Optional: 1 second delay before redirect (better UX)
                            setTimeout(() => {
                                window.location.href = "https://redvisiontechnologies.com/thanks.php";
                            }, 1000);

                        } else if (data.status === 'existing_error') {
                            document.getElementById('prev_sub_msg').innerText = data.errors;
                        } else if (data.status === 'captcha_error') {
                            document.getElementById('con_cap_msg').innerText = data.errors;
                        } else {
                            document.getElementById('form_message').innerText = data.errors ||
                                'Something went wrong!';
                        }

                        disabledButton.disabled = false; // Button enable after response
                        disabledButton.innerText = originalText;
                    })
                    .catch(() => {
                        document.getElementById('form_message').innerText = "Network error! Please try again.";
                        disabledButton.disabled = false;
                        disabledButton.innerText = originalText;
                    });
            });

